// One generator, two callers: `npm run api-types` writes web/src/api/schema.d.ts from the
// committed OpenAPI document; `npm run api-types:check` regenerates in memory and fails on drift.
// Using ONE code path for both is what makes the check trustworthy — the writer and the checker
// can never disagree about formatting. This is the frontend half of "one contract, two consumers".
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import process from 'node:process';
import openapiTS, { astToString } from 'openapi-typescript';

const specPath = fileURLToPath(new URL('../../docs/openapi/agora-v1.json', import.meta.url));
const outPath = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url));
const check = process.argv.includes('--check');

const banner =
  '// GENERATED by `npm run api-types` from docs/openapi/agora-v1.json — DO NOT EDIT BY HAND.\n' +
  '// Regenerate after blessing an OpenAPI change (AGORA_UPDATE_OPENAPI=1 dotnet test).\n\n';

const schema = JSON.parse(readFileSync(specPath, 'utf8'));
const generated = banner + astToString(await openapiTS(schema));

if (!check) {
  writeFileSync(outPath, generated);
  console.log(`Wrote ${outPath}`);
  process.exit(0);
}

let current = '';
try {
  current = readFileSync(outPath, 'utf8');
} catch {
  console.error('src/api/schema.d.ts is missing. Run `npm run api-types`.');
  process.exit(1);
}

if (current.replace(/\r\n/g, '\n') !== generated.replace(/\r\n/g, '\n')) {
  console.error(
    'API types are out of date with docs/openapi/agora-v1.json.\n' +
      'Run `npm run api-types` and commit web/src/api/schema.d.ts.',
  );
  process.exit(1);
}

console.log('API types are in sync with the committed OpenAPI document.');
